// Builds games-played-data.js — a real, historical games-played-by-finish-rank
// curve per position, replacing the flat AVG_GAMES_PLAYED guess that used to
// feed the BEER man-games replacement calc (see claude.md's "BEER / VBD"
// section for the full writeup and honest caveats about what this curve
// does and doesn't capture).
//
// Usage: node build-games-played-data.js
// Regenerate after each NFL season completes to roll the 3-season window
// forward (update SEASONS below).
//
// Source: Sleeper's public season-stats endpoint (same domain already used
// for ADP/projections/stat-columns — no new host permission), which carries
// each player's real `gp` (games played) AND `pos_rank_ppr` (their actual
// season-end positional finish rank) in one response — no separate
// historical ADP source needed to bucket players by tier.
const fs = require("fs");

const SEASONS = ["2022", "2023", "2024"]; // 3-year window — rolling average smooths one unusually healthy/unhealthy season
// K added alongside K/DST support (2026-08-26) — same real-data methodology,
// no guessing: confirmed live that Sleeper's stats endpoint carries the same
// gp/pos_rank_ppr fields for kickers as it does for QB/RB/WR/TE. DEF is
// deliberately NOT included here and never will be — a team defense is a
// fixed 32-entity pool with no waiver-replenishment churn the way an
// individual player has, so "games played by replacement depth" isn't a
// coherent question for it (same reasoning DEF is excluded from BEER
// entirely, see shared.js's BEER_POSITIONS).
const POSITIONS = ["QB", "RB", "WR", "TE", "K"];
const MAX_RANK = 60; // covers this league's deepest replacement rank (RB ~43) with real margin
const WINDOW = 4; // +/- ranks smoothed together per data point — a single exact rank has too few (season, player) pairs to be stable

async function fetchSeason(year) {
  const url = `https://api.sleeper.app/stats/nfl/${year}?season_type=regular&position[]=QB&position[]=RB&position[]=WR&position[]=TE&position[]=K&order_by=pts_ppr`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${year}`);
  return res.json();
}

(async () => {
  const points = { QB: [], RB: [], WR: [], TE: [], K: [] }; // pos -> [{rank, gp}, ...] across all seasons
  for (const year of SEASONS) {
    const rows = await fetchSeason(year);
    rows.forEach((row) => {
      const pos = row.player && row.player.position;
      if (!POSITIONS.includes(pos)) return;
      const stats = row.stats || {};
      const gp = stats.gp;
      const rank = stats.pos_rank_ppr;
      if (gp == null || rank == null) return;
      points[pos].push({ rank: Number(rank), gp: Number(gp) });
    });
    console.log(`${year}: fetched ${rows.length} rows`);
  }

  const curves = {};
  POSITIONS.forEach((pos) => {
    const curve = [];
    for (let r = 1; r <= MAX_RANK; r++) {
      const windowVals = points[pos].filter((p) => Math.abs(p.rank - r) <= WINDOW).map((p) => p.gp);
      const avg = windowVals.length
        ? windowVals.reduce((a, b) => a + b, 0) / windowVals.length
        : curve[curve.length - 1] ?? 17;
      curve.push(Math.round(avg * 100) / 100);
    }
    curves[pos] = curve;
  });

  const jsCode = `// Real historical games-played-by-finish-rank curves, per position.
// Auto-generated by build-games-played-data.js — do not hand-edit; re-run the
// script (updating SEASONS to roll the window forward) to regenerate.
//
// GAMES_PLAYED_CURVE[pos][i] = average real games played (gp) by players who
// finished that season ranked (i+1) at that position by total PPR points
// (pos_rank_ppr), smoothed across a +/-${WINDOW}-rank window and averaged
// over the ${SEASONS.join("/")} seasons. Source: Sleeper's public
// /stats/nfl/{year} endpoint — see build-games-played-data.js.
//
// Index 0 = rank 1 (the best finisher at that position that season).
// Ranks beyond ${MAX_RANK} reuse the last computed value (flat extrapolation)
// rather than guessing a further decline with no data behind it.
const GAMES_PLAYED_CURVE = ${JSON.stringify(curves, null, 2)};
`;
  fs.writeFileSync(__dirname + "/games-played-data.js", jsCode);
  console.log("Wrote games-played-data.js");
  POSITIONS.forEach((pos) => console.log(pos, curves[pos]));
})();
